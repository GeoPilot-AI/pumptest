#!/usr/bin/env python3
"""Fail the build if the architecture decision records have drifted.

A folder of decision records is not a registry. On one engagement twelve records
accumulated in `pm/decisions/` with no index, no entry in the documentation
site, and two different citation styles in the files that referenced them. The
one hand-written index, a row in the file guide, said "0001 to 0006" while 0008
existed, and the fix was to delete the range rather than update it, because
nobody was ever going to keep a list current by hand.

The reasoning behind every architectural choice on that engagement was therefore
invisible in the thing the client actually received.

So the index is generated from the records and the generation is checked. Run
with --write to regenerate it; run without to fail when it no longer matches.
That is the same shape as every other gate here: the rule is executable, or it
is a preference somebody will drop under deadline.

What this enforces:

    numbering       sequential from one, no gaps, no duplicates
    filename        NNNN-kebab-case-title.md, number matching the heading
    heading         `# N. Title` as the first line
    date            an ISO date, so the sequence can be read chronologically
    status          one of a closed set, so "superseded" means something
    supersession    a superseded record names what replaced it
    sections        Context, Decision, Consequences, all three present
    index           README.md matches the records on disk
    site            docs/decisions.md carries every record, in full and current

Usage:
    python scripts/check_decisions.py
    python scripts/check_decisions.py --write
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DECISIONS = REPO / "pm" / "decisions"
INDEX = DECISIONS / "README.md"

# The records also go into the documentation site, because the site is what a
# client actually browses and mkdocs will not read files outside docs/. One
# generated page carrying every record in full: no plugin, no dependency, and
# one source of truth rather than a copy somebody has to remember to update.
SITE_PAGE = REPO / "docs" / "decisions.md"

# A closed set, so a reader can trust the word. "draft" and "wip" and "tentative"
# are the same thing said three ways, and a record whose status is free text
# cannot be counted.
STATUSES = ("proposed", "accepted", "superseded", "deprecated", "rejected")

FILENAME = re.compile(r"^(\d{4})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$")
HEADING = re.compile(r"^#\s+(\d+)\.\s+(\S.*)$")
DATE = re.compile(r"^Date:\s*(\d{4}-\d{2}-\d{2})\s*$")
# The status text is captured loosely and validated against the closed set
# afterwards, so that `Status: sort of agreed` is reported as a status outside
# the set rather than as no status at all. The first version rejected it at the
# pattern and told the author their record had no Status line, which is untrue
# and sends them looking in the wrong place.
STATUS = re.compile(r"^Status:\s*(.+?)(?:\s+by\s+(\d+))?\s*$", re.IGNORECASE)

REQUIRED_SECTIONS = ("## Context", "## Decision", "## Consequences")

# How far into the file the header block must appear. Far enough for a blank
# line between each part, short enough that it is a header rather than prose.
HEADER_WINDOW = 8

GENERATED_NOTE = "<!-- Generated by scripts/check_decisions.py --write. Do not edit by hand. -->"

# A record's own headings start at level one. On a page that already has a
# title they have to drop a level, or every record looks like a new document.
FENCE = "```"


@dataclass
class Record:
    path: Path
    number: int
    title: str
    date: str
    status: str
    superseded_by: int | None


def _parse(path: Path, problems: list[str]) -> Record | None:
    """Read one record, reporting every problem rather than the first."""

    name_match = FILENAME.match(path.name)
    if not name_match:
        problems.append(f"{path.name}: filename is not NNNN-kebab-case-title.md")
        return None
    number = int(name_match.group(1))

    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines:
        problems.append(f"{path.name}: empty")
        return None

    heading = HEADING.match(lines[0])
    if not heading:
        problems.append(f"{path.name}: first line is not `# {number}. Title`")
        return None
    if int(heading.group(1)) != number:
        problems.append(
            f"{path.name}: heading says record {heading.group(1)}, filename says {number}"
        )

    header = lines[1 : HEADER_WINDOW + 1]
    date_at = status_at = -1
    date_line = status_line = None
    for offset, line in enumerate(header):
        if date_line is None and (match := DATE.match(line)):
            date_line, date_at = match, offset
        if status_line is None and (match := STATUS.match(line)):
            status_line, status_at = match, offset

    if date_line is None:
        problems.append(f"{path.name}: no `Date: YYYY-MM-DD` in the first {HEADER_WINDOW} lines")
    if status_line is None:
        problems.append(f"{path.name}: no `Status: <state>` in the first {HEADER_WINDOW} lines")
    if date_line is None or status_line is None:
        return None

    # One order, so a reader and a parser both know where to look. Which order
    # matters less than that every record uses the same one.
    if status_at < date_at:
        problems.append(f"{path.name}: Status is before Date; the house order is Date then Status")

    status = status_line.group(1).lower()
    if status not in STATUSES:
        problems.append(f"{path.name}: status {status!r} is not one of {', '.join(STATUSES)}")

    superseded_by = int(status_line.group(2)) if status_line.group(2) else None
    if status == "superseded" and superseded_by is None:
        problems.append(
            f"{path.name}: superseded without naming its replacement. "
            "Write `Status: superseded by N`, because a reader who finds this "
            "record needs to be sent somewhere."
        )

    body = "\n".join(lines)
    for section in REQUIRED_SECTIONS:
        if section not in body:
            problems.append(f"{path.name}: no `{section}` section")

    return Record(
        path=path,
        number=number,
        title=heading.group(2).strip(),
        date=date_line.group(1),
        status=status,
        superseded_by=superseded_by,
    )


def _check_sequence(records: list[Record], problems: list[str]) -> None:
    """Numbering is the only thing every citation in the repository depends on."""

    seen: dict[int, Path] = {}
    for record in records:
        if record.number in seen:
            problems.append(
                f"{record.path.name}: number {record.number} already used by "
                f"{seen[record.number].name}"
            )
        seen[record.number] = record.path

    if not seen:
        return
    expected = set(range(1, max(seen) + 1))
    for missing in sorted(expected - set(seen)):
        problems.append(f"record {missing:04d} is missing; the sequence has a gap")

    numbers = set(seen)
    for record in records:
        if record.superseded_by is not None and record.superseded_by not in numbers:
            problems.append(
                f"{record.path.name}: says it was superseded by {record.superseded_by}, "
                "which does not exist"
            )


def render(records: list[Record]) -> str:
    """The index, generated. Every column comes from the records themselves."""

    rows = [
        GENERATED_NOTE,
        "",
        "# Architecture decisions",
        "",
        "One file per decision that shapes the architecture or a delivery boundary.",
        "Records are immutable once accepted: a decision that changes course gets its",
        "own record and supersedes the earlier one by reference.",
        "",
        "| # | Decision | Date | Status |",
        "|---|---|---|---|",
    ]
    for record in sorted(records, key=lambda r: r.number):
        status = record.status
        if record.superseded_by is not None:
            target = _link(records, record.superseded_by)
            status = f"superseded by [{record.superseded_by}]({target})"
        rows.append(
            f"| {record.number} | [{record.title}]({record.path.name}) | {record.date} | {status} |"
        )
    rows.append("")
    return "\n".join(rows)


def _demote(body: str) -> str:
    """Drop every heading one level, leaving fenced blocks alone.

    A comment inside a fenced block starts with a hash and is not a heading.
    No record uses a fence today, which is exactly why this is handled now
    rather than after the first one does and the page quietly grows a heading
    called `#!/usr/bin/env python3`.
    """

    out = []
    in_fence = False
    for line in body.splitlines():
        if line.lstrip().startswith(FENCE):
            in_fence = not in_fence
        elif not in_fence and line.startswith("#"):
            line = "#" + line
        out.append(line)
    return "\n".join(out)


def render_page(records: list[Record]) -> str:
    """Every record, in full, on one page the documentation site can carry."""

    parts = [
        GENERATED_NOTE,
        "",
        "# Architecture decisions",
        "",
        "Why this system is the way it is. One record per decision that shapes the",
        "architecture or a delivery boundary, in the order they were taken.",
        "",
        "Records are immutable once accepted. A decision that changes course gets its own",
        "record and supersedes the earlier one by reference, rather than the earlier one",
        "being edited to agree with the present.",
        "",
        "This page is generated from `pm/decisions/`. Edit a record there, then run",
        "`python scripts/check_decisions.py --write`.",
        "",
    ]
    for record in sorted(records, key=lambda r: r.number):
        parts.append(_demote(record.path.read_text(encoding="utf-8")).rstrip())
        parts.append("")
    # Exactly one trailing newline. The first version left two, and
    # end-of-file-fixer stripped one the moment the file was staged, so the
    # generator and the repository's own hooks disagreed about the output and
    # the next run of the gate failed on a file nobody had touched.
    return "\n".join(parts).rstrip("\n") + "\n"


def _rel(path: Path) -> str:
    """A path for a message, never a reason to raise.

    relative_to raises when the path sits outside REPO, which happens the moment
    a caller redirects one root and not another. Reporting is not the place to
    fail.
    """

    try:
        return str(path.relative_to(REPO))
    except ValueError:
        return str(path)


def _link(records: list[Record], number: int) -> str:
    for record in records:
        if record.number == number:
            return record.path.name
    return "#"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the index")
    args = parser.parse_args(argv)

    if not DECISIONS.is_dir():
        print(f"No decision records at {_rel(DECISIONS)}.")
        print("Every repository gets record 0001. Run install_gates.py, or write it.")
        return 1

    files = sorted(p for p in DECISIONS.glob("*.md") if p.name != "README.md")
    if not files:
        print(f"{_rel(DECISIONS)} holds no records.")
        return 1

    problems: list[str] = []
    records = [r for p in files if (r := _parse(p, problems)) is not None]
    _check_sequence(records, problems)

    expected = render(records)
    expected_page = render_page(records)
    plural = "" if len(records) == 1 else "s"

    if args.write:
        INDEX.write_text(expected, encoding="utf-8", newline="")
        written = [INDEX]
        # The site page is written only where a site exists. A repository with
        # no docs/ has not opted into one, and generating a page into a
        # directory nobody publishes would be a file nobody reads.
        if SITE_PAGE.parent.is_dir():
            SITE_PAGE.write_text(expected_page, encoding="utf-8", newline="")
            written.append(SITE_PAGE)
        where = " and ".join(_rel(p) for p in written)
        print(f"wrote {where}, {len(records)} record{plural}")
        return 0 if not problems else _report(problems)

    actual = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
    if actual != expected:
        problems.append(
            "pm/decisions/README.md does not match the records. "
            "Run: python scripts/check_decisions.py --write"
        )

    if SITE_PAGE.parent.is_dir():
        actual_page = SITE_PAGE.read_text(encoding="utf-8") if SITE_PAGE.exists() else ""
        if actual_page != expected_page:
            problems.append(
                f"{_rel(SITE_PAGE)} does not match the records, so the "
                "documentation site the client reads is out of date. "
                "Run: python scripts/check_decisions.py --write"
            )

    if problems:
        return _report(problems)

    plural = "" if len(records) == 1 else "s"
    print(f"{len(records)} decision record{plural}, indexed and consistent.")
    return 0


def _report(problems: list[str]) -> int:
    print("Architecture decision records:")
    for problem in problems:
        print(f"  {problem}")
    print(
        "\nA decision nobody can find is a decision that gets made again, "
        "differently, by whoever is next."
    )
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
